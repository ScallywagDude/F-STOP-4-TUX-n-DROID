#!/usr/bin/env python
# Writes game/shared/fstop_csstubs/cs_gamerules.h: a CS game rules stand-in for the F-STOP build.
# Collects every CSGameRules()->Method name the non-CS base files call.
#   gen_cs_stubs.py
import os, re
SRC = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'src', 'game')
CALL = re.compile(r'CSGameRules\(\)\s*->\s*(\w+)')
SKIP = re.compile(r'cstrike15|[/\\]cs_|[/\\]cstrike[/\\]|[/\\]sdk[/\\]|fstop_csstubs', re.I)
found = set()
for sub in ('client', 'server', 'shared'):
    for root, dirs, files in os.walk(os.path.join(SRC, sub)):
        for f in files:
            path = os.path.join(root, f)
            if f.endswith(('.cpp', '.h')) and not SKIP.search(path):
                found.update(CALL.findall(open(path, encoding='latin-1').read()))
names = sorted(found)
out='''//=============================================================================
// F-STOP on the CS:GO partner engine: stand-in for the CS:GO game rules header.
//
// The CS:GO base code asks the CS game rules about rounds, warmup, survival mode and so on,
// almost always as "if ( CSGameRules() && CSGameRules()->Something() )". F-STOP has no CS game
// rules, so CSGameRules() is always NULL here and those branches never run. The methods below
// exist only so that code compiles; they are never called on a real object.
// GENERATED by tools/gen_cs_stubs.py from the calls the compiled base files make.
//=============================================================================
#ifndef FSTOP_CS_GAMERULES_STUB_H
#define FSTOP_CS_GAMERULES_STUB_H
#ifdef _WIN32
#pragma once
#endif

#ifndef FSTOP_PORTAL
#error "fstop_csstubs is only for the F-STOP build; CS:GO builds use shared/cstrike15/cs_gamerules.h"
#endif

// Converts to whatever the caller expects (false, 0, NULL...).
struct FStopNoCSValue
{
	template< class T > operator T() const { return T(); }
};

class CSurvivalGameRules;

class CCSGameRules
{
public:
'''
for n in names:
    out+='\ttemplate< typename... Args > FStopNoCSValue %s( Args&&... ) const { return FStopNoCSValue(); }\n' % n
out+='''};
typedef CCSGameRules C_CSGameRules;

inline CCSGameRules *CSGameRules() { return NULL; }

#endif // FSTOP_CS_GAMERULES_STUB_H
'''
open(os.path.join(SRC, 'shared', 'fstop_csstubs', 'cs_gamerules.h'), 'w', newline='\r\n').write(out)
print(len(names))
